def main(out="data/dataset.jsonl"):
    rows, seen = [], set()
    for topic, label, answer, questions in TOPICS:
        for q in questions:
            assert q.lower() not in seen, f"duplicate question: {q}"
            seen.add(q.lower())
            rows.append({"topic": topic, "question": q, "answer": answer, "label": label})
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n",
                         encoding="utf-8")
    counts = {}
    for r in rows:
        counts[r["label"]] = counts.get(r["label"], 0) + 1
    print(f"Wrote {len(rows)} rows to {out}: {counts}")


if __name__ == "__main__":
    main()
